import json


def _serialize_json(value, field_name):
    try:
        return json.dumps(
            value,
            ensure_ascii=False,
            sort_keys=True,
            allow_nan=False,
        )
    except (TypeError, ValueError) as error:
        raise ValueError(
            f"{field_name} must contain valid JSON data."
        ) from error


def create_research_experiment(
    experiment_id,
    experiment_name,
    dataset_id,
    dataset_version,
    schema_version,
    dataset_sha256,
    manifest_sha256,
    dataset_path,
    manifest_path,
    run_type,
    manifest_status,
    random_seed,
    trials,
    warmup_trials,
    configuration,
):
    required_strings = {
        "experiment_id": experiment_id,
        "experiment_name": experiment_name,
        "dataset_id": dataset_id,
        "dataset_version": dataset_version,
        "schema_version": schema_version,
        "dataset_sha256": dataset_sha256,
        "manifest_sha256": manifest_sha256,
        "dataset_path": dataset_path,
        "manifest_path": manifest_path,
        "run_type": run_type,
        "manifest_status": manifest_status,
    }

    for field, value in required_strings.items():
        if not isinstance(value, str) or not value.strip():
            raise ValueError(f"{field} must be a non-empty string.")

    for field, value in (
        ("dataset_sha256", dataset_sha256),
        ("manifest_sha256", manifest_sha256),
    ):
        if (
            len(value) != 64
            or any(c not in "0123456789abcdefABCDEF" for c in value)
        ):
            raise ValueError(f"{field} must be a valid SHA-256 hash.")

    if type(random_seed) is not int:
        raise ValueError("Random seed must be an integer.")

    if type(trials) is not int or trials < 1:
        raise ValueError("Trials must be a positive integer.")

    if type(warmup_trials) is not int or warmup_trials < 0:
        raise ValueError("Warm-up trials must be non-negative.")

    if not isinstance(configuration, dict):
        raise ValueError("Configuration must be a dictionary.")

    configuration_json = _serialize_json(
        configuration,
        "Configuration",
    )

    with get_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                INSERT INTO research_experiments (
                    experiment_id,
                    experiment_name,
                    dataset_id,
                    dataset_version,
                    schema_version,
                    dataset_sha256,
                    manifest_sha256,
                    dataset_path,
                    manifest_path,
                    run_type,
                    manifest_status,
                    random_seed,
                    trials,
                    warmup_trials,
                    configuration_json
                )
                VALUES (
                    %s, %s, %s, %s, %s, %s, %s, %s,
                    %s, %s, %s, %s, %s, %s, %s
                )
                RETURNING id
                """,
                (
                    experiment_id,
                    experiment_name,
                    dataset_id,
                    dataset_version,
                    schema_version,
                    dataset_sha256,
                    manifest_sha256,
                    dataset_path,
                    manifest_path,
                    run_type,
                    manifest_status,
                    random_seed,
                    trials,
                    warmup_trials,
                    configuration_json,
                ),
            )
            return cursor.fetchone()[0]


