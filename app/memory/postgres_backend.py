def save_research_trial_result(
    experiment_id,
    case_id,
    strategy_id,
    trial_number,
    is_warmup,
    execution_success,
    is_correct,
    execution_time_seconds=None,
    error_type=None,
    error_message=None,
    execution_details=None,
):
    for field, value in (
        ("experiment_id", experiment_id),
        ("case_id", case_id),
        ("strategy_id", strategy_id),
    ):
        if not isinstance(value, str) or not value.strip():
            raise ValueError(f"{field} must be a non-empty string.")

    if type(trial_number) is not int or trial_number < 1:
        raise ValueError("Trial number must be a positive integer.")

    for field, value in (
        ("is_warmup", is_warmup),
        ("execution_success", execution_success),
        ("is_correct", is_correct),
    ):
        if type(value) is not bool:
            raise ValueError(f"{field} must be a boolean.")

    if execution_time_seconds is not None:
        if (
            not isinstance(execution_time_seconds, (int, float))
            or isinstance(execution_time_seconds, bool)
            or execution_time_seconds < 0
        ):
            raise ValueError(
                "Execution time must be a non-negative number or None."
            )

    for field, value in (
        ("error_type", error_type),
        ("error_message", error_message),
    ):
        if value is not None and not isinstance(value, str):
            raise ValueError(f"{field} must be a string or None.")

    execution_details_json = None

    if execution_details is not None:
        if not isinstance(execution_details, dict):
            raise ValueError(
                "Execution details must be a dictionary or None."
            )

        execution_details_json = _serialize_json(
            execution_details,
            "Execution details",
        )

    with get_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                INSERT INTO research_trial_results (
                    experiment_id,
                    case_id,
                    strategy_id,
                    trial_number,
                    is_warmup,
                    execution_success,
                    is_correct,
                    execution_time_seconds,
                    error_type,
                    error_message,
                    execution_details_json
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s)
                RETURNING id
                """,
                (
                    experiment_id,
                    case_id,
                    strategy_id,
                    trial_number,
                    is_warmup,
                    execution_success,
                    is_correct,
                    execution_time_seconds,
                    error_type,
                    error_message,
                    execution_details_json,
                ),
            )
            return cursor.fetchone()[0]


def update_research_experiment_status(
    experiment_id,
    status,
    total_cases=None,
    error_message=None,
):
    if not isinstance(experiment_id, str) or not experiment_id.strip():
        raise ValueError("Experiment ID must be a non-empty string.")

    if status not in ("running", "completed", "failed"):
        raise ValueError("Invalid research experiment status.")

    if total_cases is not None:
        if type(total_cases) is not int or total_cases < 0:
            raise ValueError(
                "Total cases must be a non-negative integer."
            )

    if error_message is not None and not isinstance(error_message, str):
        raise ValueError("Error message must be a string or None.")

    with get_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                UPDATE research_experiments
                SET status = %s,
                    total_cases = COALESCE(%s, total_cases),
                    error_message = %s,
                    completed_at = CASE
                        WHEN %s IN ('completed', 'failed')
                        THEN CURRENT_TIMESTAMP
                        ELSE NULL
                    END
                WHERE experiment_id = %s
                """,
                (
                    status,
                    total_cases,
                    error_message,
                    status,
                    experiment_id,
                ),
            )

            if cursor.rowcount == 0:
                raise ValueError("Research experiment was not found.")

            return True


