def save_user_memory(
    user_id,
    memory_key,
    content,
    category,
    source_type,
    source_text,
):
    """
    Save an explicit personal fact or correction.

    Previous versions are retained as superseded records.
    A transaction-level advisory lock serializes updates to
    the same user's memory key.
    """

    user_id = _validate_user_id(user_id)

    fields = {
        "memory_key": memory_key,
        "content": content,
        "category": category,
        "source_text": source_text,
    }

    for field, value in fields.items():
        if not isinstance(value, str) or not value.strip():
            raise ValueError(f"{field} must be a non-empty string.")

    memory_key = memory_key.strip()
    content = content.strip()
    category = category.strip()
    source_text = source_text.strip()

    if source_type not in (
        "explicit_statement",
        "correction",
    ):
        raise ValueError(
            "Source type must be 'explicit_statement' or 'correction'."
        )

    memory_id = str(uuid.uuid4())

    with get_connection() as connection:
        with connection.cursor() as cursor:

            # Serialize concurrent changes to this user/key pair.
            cursor.execute(
                """
                SELECT pg_advisory_xact_lock(
                    hashtext(%s),
                    hashtext(%s)
                )
                """,
                (user_id, memory_key),
            )

            cursor.execute(
                """
                UPDATE user_memories
                SET status = 'superseded',
                    updated_at = CURRENT_TIMESTAMP
                WHERE user_id = %s
                  AND memory_key = %s
                  AND status = 'active'
                """,
                (user_id, memory_key),
            )

            cursor.execute(
                """
                INSERT INTO user_memories (
                    id,
                    user_id,
                    memory_key,
                    content,
                    category,
                    source_type,
                    source_text,
                    status
                )
                VALUES (%s, %s, %s, %s, %s, %s, %s, 'active')
                """,
                (
                    memory_id,
                    user_id,
                    memory_key,
                    content,
                    category,
                    source_type,
                    source_text,
                ),
            )

    return memory_id


def get_user_memories(user_id, category=None, limit=None):
    """Retrieve active personal memories belonging to one user."""

    user_id = _validate_user_id(user_id)

    if category is not None:
        if not isinstance(category, str) or not category.strip():
            raise ValueError("Category must be a non-empty string or None.")

    if limit is not None:
        if type(limit) is not int or limit < 1:
            raise ValueError("Limit must be a positive integer or None.")

    query = """
        SELECT
            id,
            user_id,
            memory_key,
            content,
            category,
            source_type,
            source_text,
            status,
            created_at,
            updated_at
        FROM user_memories
        WHERE user_id = %s
          AND status = 'active'
    """

    parameters = [user_id]

    if category is not None:
        query += " AND category = %s"
        parameters.append(category.strip())

    query += " ORDER BY updated_at DESC, id DESC"

    if limit is not None:
        query += " LIMIT %s"
        parameters.append(limit)

    with get_connection() as connection:
        with connection.cursor(row_factory=dict_row) as cursor:
            cursor.execute(query, parameters)
            return cursor.fetchall()


