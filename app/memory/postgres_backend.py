
"""
AEGIS PostgreSQL persistence backend.

This module is separate from database.py so the existing
SQLite implementation and its tests remain untouched.
"""

import json
import os
import uuid

import psycopg
from psycopg.rows import dict_row


DATABASE_URL = os.getenv("AEGIS_DATABASE_URL", "").strip()


def get_connection():
    """Create a PostgreSQL connection using the configured URL."""

    if not DATABASE_URL:
        raise RuntimeError(
            "AEGIS_DATABASE_URL is not configured. "
            "Set it before using the PostgreSQL backend."
        )

    return psycopg.connect(
        DATABASE_URL,
        connect_timeout=10,
        sslmode="require",
    )


def _validate_user_id(user_id):
    """Validate an authenticated user's ID."""

    if not isinstance(user_id, str) or not user_id.strip():
        raise ValueError("User ID must be a non-empty string.")

    return user_id.strip()


def initialize_database():
    """
    Create the AEGIS PostgreSQL schema.

    All statements are idempotent. Existing tables and records
    are not dropped, truncated, or overwritten.
    """

    statements = [
        """
        CREATE TABLE IF NOT EXISTS feedback (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            task TEXT NOT NULL,
            rating INTEGER NOT NULL CHECK (rating BETWEEN 1 AND 5),
            comment TEXT DEFAULT '',
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            strategy_id TEXT
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS benchmark_results (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            task TEXT NOT NULL,
            strategy_id TEXT NOT NULL,
            total_trials INTEGER NOT NULL,
            successful_runs INTEGER NOT NULL,
            failed_runs INTEGER NOT NULL,
            average_execution_time DOUBLE PRECISION NOT NULL,
            correct BOOLEAN NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS research_experiments (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            experiment_id TEXT NOT NULL UNIQUE,
            experiment_name TEXT NOT NULL,
            dataset_id TEXT NOT NULL,
            dataset_version TEXT NOT NULL,
            schema_version TEXT NOT NULL,
            dataset_sha256 TEXT NOT NULL,
            manifest_sha256 TEXT NOT NULL,
            dataset_path TEXT NOT NULL,
            manifest_path TEXT NOT NULL,
            run_type TEXT NOT NULL,
            manifest_status TEXT NOT NULL,
            random_seed INTEGER NOT NULL,
            trials INTEGER NOT NULL,
            warmup_trials INTEGER NOT NULL,
            configuration_json TEXT NOT NULL,
            status TEXT NOT NULL DEFAULT 'running',
            total_cases INTEGER NOT NULL DEFAULT 0,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            completed_at TIMESTAMP,
            error_message TEXT
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS research_case_results (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            experiment_id TEXT NOT NULL,
            case_id TEXT NOT NULL,
            category TEXT NOT NULL,
            difficulty TEXT NOT NULL,
            group_id TEXT NOT NULL,
            validation_status TEXT NOT NULL,
            expected_outcome_json TEXT NOT NULL,
            case_status TEXT NOT NULL,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            UNIQUE (experiment_id, case_id),
            FOREIGN KEY (experiment_id)
                REFERENCES research_experiments(experiment_id)
                ON DELETE CASCADE
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS research_trial_results (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            experiment_id TEXT NOT NULL,
            case_id TEXT NOT NULL,
            strategy_id TEXT NOT NULL,
            trial_number INTEGER NOT NULL,
            is_warmup BOOLEAN NOT NULL DEFAULT FALSE,
            execution_success BOOLEAN NOT NULL,
            is_correct BOOLEAN NOT NULL,
            execution_time_seconds DOUBLE PRECISION,
            error_type TEXT,
            error_message TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            execution_details_json TEXT,
            FOREIGN KEY (experiment_id, case_id)
                REFERENCES research_case_results(experiment_id, case_id)
                ON DELETE CASCADE
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS conversations (
            id TEXT PRIMARY KEY,
            title TEXT NOT NULL DEFAULT 'New conversation',
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
        """,
        """
        ALTER TABLE conversations
        ADD COLUMN IF NOT EXISTS user_id TEXT
        """,
        """
        CREATE INDEX IF NOT EXISTS idx_conversations_user_updated
        ON conversations(user_id, updated_at DESC)
        """,
        """
        CREATE TABLE IF NOT EXISTS conversation_messages (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            conversation_id TEXT NOT NULL,
            role TEXT NOT NULL CHECK (role IN ('user', 'assistant')),
            content TEXT NOT NULL,
            tool_name TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            FOREIGN KEY (conversation_id)
                REFERENCES conversations(id)
                ON DELETE CASCADE
        )
        """,
        """
        CREATE TABLE IF NOT EXISTS user_memories (
            id TEXT PRIMARY KEY,
            user_id TEXT NOT NULL,
            memory_key TEXT NOT NULL,
            content TEXT NOT NULL,
            category TEXT NOT NULL,
            source_type TEXT NOT NULL
                CHECK (
                    source_type IN (
                        'explicit_statement',
                        'correction'
                    )
                ),
            source_text TEXT NOT NULL,
            status TEXT NOT NULL DEFAULT 'active'
                CHECK (status IN ('active', 'superseded')),
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            CHECK (length(trim(user_id)) > 0),
            CHECK (length(trim(memory_key)) > 0),
            CHECK (length(trim(content)) > 0),
            CHECK (length(trim(category)) > 0),
            CHECK (length(trim(source_text)) > 0)
        )
        """,
        """
        CREATE UNIQUE INDEX IF NOT EXISTS
        idx_user_memories_unique_active_key
        ON user_memories(user_id, memory_key)
        WHERE status = 'active'
        """,
        """
        CREATE INDEX IF NOT EXISTS
        idx_user_memories_owner_status
        ON user_memories(user_id, status)
        """,
        """
        CREATE INDEX IF NOT EXISTS
        idx_user_memories_owner_key
        ON user_memories(user_id, memory_key)
        """,
        """
        CREATE INDEX IF NOT EXISTS idx_research_cases_experiment
        ON research_case_results(experiment_id)
        """,
        """
        CREATE INDEX IF NOT EXISTS idx_research_cases_category
        ON research_case_results(category, difficulty)
        """,
        """
        CREATE INDEX IF NOT EXISTS idx_research_trials_experiment
        ON research_trial_results(experiment_id)
        """,
        """
        CREATE INDEX IF NOT EXISTS idx_research_trials_strategy
        ON research_trial_results(strategy_id)
        """,
        """
        CREATE INDEX IF NOT EXISTS idx_conversation_messages_history
        ON conversation_messages(conversation_id, id)
        """,
    ]

    with get_connection() as connection:
        with connection.cursor() as cursor:
            for statement in statements:
                cursor.execute(statement)


