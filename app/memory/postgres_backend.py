def create_conversation(title="New conversation"):
    """Create a conversation and return its unique ID."""

    import uuid

    if not isinstance(title, str) or not title.strip():
        raise ValueError("Conversation title must be a non-empty string.")

    conversation_id = str(uuid.uuid4())

    with get_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                INSERT INTO conversations (id, title)
                VALUES (%s, %s)
                """,
                (conversation_id, title.strip()[:100]),
            )

    return conversation_id


def save_conversation_message(
    conversation_id,
    role,
    content,
    tool_name=None,
):
    """Persist one user or assistant message."""

    if not isinstance(conversation_id, str) or not conversation_id.strip():
        raise ValueError("Conversation ID must be a non-empty string.")

    if role not in ("user", "assistant"):
        raise ValueError("Role must be 'user' or 'assistant'.")

    if not isinstance(content, str) or not content.strip():
        raise ValueError("Message content must be a non-empty string.")

    if tool_name is not None and not isinstance(tool_name, str):
        raise ValueError("Tool name must be a string or None.")

    with get_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                SELECT id
                FROM conversations
                WHERE id = %s
                """,
                (conversation_id,),
            )

            if cursor.fetchone() is None:
                raise ValueError("Conversation was not found.")

            cursor.execute(
                """
                INSERT INTO conversation_messages (
                    conversation_id,
                    role,
                    content,
                    tool_name
                )
                VALUES (%s, %s, %s, %s)
                RETURNING id
                """,
                (
                    conversation_id,
                    role,
                    content,
                    tool_name,
                ),
            )

            message_id = cursor.fetchone()[0]

            if role == "user":
                cursor.execute(
                    """
                    UPDATE conversations
                    SET title = CASE
                        WHEN title = 'New conversation'
                        THEN %s
                        ELSE title
                    END,
                    updated_at = CURRENT_TIMESTAMP
                    WHERE id = %s
                    """,
                    (content.strip()[:100], conversation_id),
                )
            else:
                cursor.execute(
                    """
                    UPDATE conversations
                    SET updated_at = CURRENT_TIMESTAMP
                    WHERE id = %s
                    """,
                    (conversation_id,),
                )

            return message_id


def get_conversation_messages(conversation_id, limit=None):
    """Retrieve messages in chronological order."""

    if not isinstance(conversation_id, str) or not conversation_id.strip():
        raise ValueError("Conversation ID must be a non-empty string.")

    if limit is not None:
        if type(limit) is not int or limit < 1:
            raise ValueError("Limit must be a positive integer or None.")

    with get_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                SELECT id
                FROM conversations
                WHERE id = %s
                """,
                (conversation_id,),
            )

            if cursor.fetchone() is None:
                raise ValueError("Conversation was not found.")

        with connection.cursor(row_factory=dict_row) as cursor:
            if limit is None:
                cursor.execute(
                    """
                    SELECT
                        id,
                        conversation_id,
                        role,
                        content,
                        tool_name,
                        created_at
                    FROM conversation_messages
                    WHERE conversation_id = %s
                    ORDER BY id ASC
                    """,
                    (conversation_id,),
                )
            else:
                cursor.execute(
                    """
                    SELECT
                        id,
                        conversation_id,
                        role,
                        content,
                        tool_name,
                        created_at
                    FROM (
                        SELECT *
                        FROM conversation_messages
                        WHERE conversation_id = %s
                        ORDER BY id DESC
                        LIMIT %s
                    ) AS recent_messages
                    ORDER BY id ASC
                    """,
                    (conversation_id, limit),
                )

            return cursor.fetchall()


def get_all_conversations():
    """Retrieve conversation summaries, newest first."""

    with get_connection() as connection:
        with connection.cursor(row_factory=dict_row) as cursor:
            cursor.execute(
                """
                SELECT
                    c.id,
                    c.title,
                    c.created_at,
                    c.updated_at,
                    COUNT(m.id) AS message_count
                FROM conversations AS c
                LEFT JOIN conversation_messages AS m
                    ON c.id = m.conversation_id
                GROUP BY c.id
                ORDER BY c.updated_at DESC, c.id DESC
                """
            )

            return cursor.fetchall()


def delete_conversation(conversation_id):
    """Delete a conversation and its messages."""

    if not isinstance(conversation_id, str) or not conversation_id.strip():
        raise ValueError("Conversation ID must be a non-empty string.")

    with get_connection() as connection:
        with connection.cursor() as cursor:
            cursor.execute(
                """
                DELETE FROM conversations
                WHERE id = %s
                """,
                (conversation_id,),
            )

            if cursor.rowcount == 0:
                raise ValueError("Conversation was not found.")

            return True

